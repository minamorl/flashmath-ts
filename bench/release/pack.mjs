import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
const root=process.cwd();
assert.ok(process.env.TMPDIR,'TMPDIR is required');
const npmCache=fs.mkdtempSync(path.join(process.env.TMPDIR,'flashmath-npm-cache-'));
process.env.npm_config_cache=npmCache;
process.on('exit',()=>fs.rmSync(npmCache,{recursive:true,force:true}));
const run=(cmd,args,options={})=>{
 const p=spawnSync(cmd,args,{encoding:'utf8',maxBuffer:8e6,...options});
 if(p.status!==0)throw Error(`${cmd} exit ${p.status}\n${p.stdout}\n${p.stderr}`);
 return p.stdout;
};
const packed=JSON.parse(run('npm',['pack','--ignore-scripts','--json','--pack-destination','bench/release']));
const info=packed[0],tarball=path.join(root,'bench/release',info.filename);
assert.equal(info.name,'@minamorl/flashmath');assert.equal(info.version,'0.1.0');
assert.ok(info.files.every(f=>/^(dist\/|README.md$|LICENSE$|NOTICE$|package.json$)/.test(f.path)));
assert.ok(info.files.some(f=>f.path==='dist/fonts.css'));
assert.equal(info.files.filter(f=>f.path.endsWith('.woff2')).length,4);
fs.writeFileSync('bench/release/pack.json',JSON.stringify(info,null,2)+'\n');
const listing=run('tar',['-tvzf',tarball]);fs.writeFileSync('bench/release/tarball-files.txt',listing);
assert.ok(process.env.TMPDIR,'TMPDIR is required');
const folder=fs.mkdtempSync(path.join(process.env.TMPDIR,'flashmath-pack-'));
try{
 const modules=path.join(folder,'node_modules'),pkg=path.join(modules,'@minamorl/flashmath');
 fs.mkdirSync(pkg,{recursive:true});run('tar',['-xzf',tarball,'--strip-components=1','-C',pkg]);
 fs.writeFileSync(path.join(folder,'core.mjs'),`import assert from 'node:assert/strict';
import {parseToMathMLAst,toMathMLString,createMathMLParser} from '@minamorl/flashmath';
const xml=toMathMLString(parseToMathMLAst(String.raw\`\\frac{a}{b}\`));
assert.ok(xml.includes('<mfrac>'));assert.ok(createMathMLParser().parse('x'));
console.log('Packed core import and parse: PASS (React absent)');\n`);
 const core=run(process.execPath,['core.mjs'],{cwd:folder});
 for(const name of ['react','react-dom'])fs.symlinkSync(fs.realpathSync(path.join(root,'node_modules',name)),path.join(modules,name),'dir');
 fs.writeFileSync(path.join(folder,'react.mjs'),`import assert from 'node:assert/strict';
import fs from 'node:fs';
import {parseToMathMLAst,toMathMLString} from '@minamorl/flashmath';
import {parseToReact} from '@minamorl/flashmath/react';
import {renderToStaticMarkup} from 'react-dom/server';
const tex=String.raw\`\\frac{x}{\\sqrt{y}}\`;
assert.equal(renderToStaticMarkup(parseToReact(tex)),toMathMLString(parseToMathMLAst(tex)));
const proof=String.raw\`\\begin{prooftree}\\Axiom$A \\fCenter B$\\UnaryInf$A \\fCenter C$\\end{prooftree}\`;
assert.ok(!renderToStaticMarkup(parseToReact(proof,{packages:['base','bussproofs']})).includes('<merror'));
assert.ok(fs.readFileSync(new URL(import.meta.resolve('@minamorl/flashmath/fonts.css')),'utf8').includes('@font-face'));
console.log('Packed react import, React SSR, sequent and font export: PASS');\n`);
 const react=run(process.execPath,['react.mjs'],{cwd:folder});
 console.log(core.trim());console.log(react.trim());
 console.log(`${info.filename}: ${info.size} bytes packed, ${info.unpackedSize} bytes unpacked`);
 console.log(`sha512 integrity: ${info.integrity}`);
}finally{fs.rmSync(folder,{recursive:true,force:true});}
