import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
const root=process.cwd(),dir=path.join(root,'bench/hardening/pack-consumer');
const run=(cmd,args,options={})=>{const r=spawnSync(cmd,args,{encoding:'utf8',...options});if(r.status!==0)throw Error(`${cmd} exit ${r.status}\n${r.stdout}\n${r.stderr}`);return r.stdout;};
const meta=JSON.parse(run('npm',['pack','--json','--cache',path.join(root,'node_modules/.npm-cache'),'--pack-destination','bench/flashmath']))[0];
assert.equal(meta.name,'@minamorl/flashmath');assert.equal(meta.version,'0.1.0');
for(const file of meta.files)assert.match(file.path,/^(dist\/|README\.md$|LICENSE$|NOTICE$|package\.json$)/);
assert.ok(meta.files.some(f=>f.path==='dist/index.js'));assert.ok(meta.files.some(f=>f.path==='dist/react.js'));
fs.rmSync(dir,{recursive:true,force:true});
const target=path.join(dir,'node_modules/@minamorl/flashmath');fs.mkdirSync(target,{recursive:true});
run('tar',['-xzf',path.join(root,'bench/flashmath',meta.filename),'-C',target,'--strip-components=1']);
for(const name of ['react','react-dom'])fs.symlinkSync(path.join(root,'node_modules',name),path.join(dir,'node_modules',name),'dir');
fs.writeFileSync(path.join(dir,'smoke.mjs'),`import assert from 'node:assert/strict';
import {parseToMathMLAst,toMathMLString} from '@minamorl/flashmath';
import {parseToReact} from '@minamorl/flashmath/react';
import {renderToStaticMarkup} from 'react-dom/server';
const tex=String.raw\`\\begin{cases}x&x>0\\\\0&x=0\\end{cases}\`;
const opts={packages:['base','ams'],display:true};
const core=toMathMLString(parseToMathMLAst(tex,opts));const react=renderToStaticMarkup(parseToReact(tex,opts));
assert.match(core,/<mtable/);assert.match(react,/<mtable/);assert.doesNotMatch(core+react,/merror/);
console.log(JSON.stringify({coreImport:true,reactImport:true,coreBytes:core.length,reactBytes:react.length}));
`);
const stdout=run(process.execPath,['smoke.mjs'],{cwd:dir});
fs.writeFileSync(path.join(root,'bench/flashmath/pack-manifest.json'),JSON.stringify(meta,null,2)+'\n');
console.log(stdout.trim());console.log(JSON.stringify({tarball:meta.filename,files:meta.files.length,unpackedBytes:meta.unpackedSize}));
fs.rmSync(dir,{recursive:true,force:true});
